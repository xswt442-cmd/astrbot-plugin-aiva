# 凭记忆写错过四个（「亚述」「霜寒城谣」「莲华」「日落城」都是错的，
# 「禁地龛境」干脆是编出来的名字）。接口自己也会返回 used_map.name，
# 有数据时优先用他打过的图（见 `_pick地图`）。
地图池 = (
    "亚海悬城",  # Ascent
    "霓虹町",  # Split
    "裂变峡谷",  # Fracture
    "源工重镇",  # Bind
    "微风岛屿",  # Breeze
    "盐海矿镇",  # Haven
    "深海明珠",  # Pearl
    "森寒冬港",  # Icebox
    "莲华古城",  # Lotus
    "日落之城",  # Sunset
    "幽邃地窟",  # Abyss
)

# 四大定位与常选特工，名字同样取自有数据的 `valorant-api.com/v1/agents`。
# 推演里写定位，模型才好接着说：写「决斗」它能推进点节奏，
# 写「哨卫」它能推守点与蹲守。
特工池 = {
    "决斗": ("捷风", "雷兹", "不死鸟", "霓虹", "芮娜", "夜露", "幻棱"),
    "先锋": ("铁臂", "猎枭", "钛狐", "盖可", "黑梦", "斯凯", "K/O"),
    "控场": ("蝰蛇", "海神", "星礈", "迷核", "幽影", "暮蝶", "炼狱"),
    "哨卫": ("尚勃勒", "奇乐", "钢锁", "维斯", "零", "贤者", "禁灭"),
}

_定位说明 = {
    "决斗": "负责进点 opening，站在队伍第一个身位，也是第一枪大概率由他开",
    "先锋": "负责闪光与侦查，走在队伍第二个身位，进了点先把交叉火力点清掉",
    "控场": "负责切线压烟，进点前把关键枪线封住，决定队友能站在哪儿",
    "哨卫": "看住侧翼与回防，进点后留在后场听 rotation、拖住绕后的人",
}


def 选地图(随机源: random.Random, 偏好: tuple[str, ...] = ()) -> str:
    """挑一张图。

    `偏好` 传进来就用它——那是他真打过的图（`stats.地图一览`），
    名字也是接口给的，比这张常量表可靠。为空才退回常量表。
    """
    if 偏好:
        return 随机源.choice(偏好)
    return 随机源.choice(地图池)


def 选特工(随机源: random.Random) -> tuple[str, str]:
    """返回一个 `(定位, 特工名)`。"""
    定位 = 随机源.choice(tuple(特工池))
    return 定位, 随机源.choice(特工池[定位])


def 常规比分(随机源: random.Random) -> tuple[int, int]:
    """一个合法的常规时间比分：先到 13 且落差合理。"""
    if 随机源.random() < 0.5:
        输分 = 随机源.choice((5, 7, 8, 9, 10, 11))
        return 13, 输分
    输分 = 随机源.choice((5, 7, 8, 9, 10, 11))
    return 输分, 13


def 加时比分(随机源: random.Random) -> tuple[int, int]:
    """加时：12:12 之后净胜 2 回合，先到 14 才算赢，之后每多一轮再加 1 分。

    这里直接给终值，形式上是 `n+2 : n`。
    """
    底 = 12 + 随机源.choice((0, 1, 2, 3))
    赢 = 底 + 2
    return (赢, 底) if 随机源.random() < 0.5 else (底, 赢)


def 开局设定(随机源: random.Random, 摘要: dict[str, Any] | None) -> dict[str, Any]:
    """生成一局的完整设定。

    `摘要` 是玩家真实的近期统计（`aiva.stats.聚合` 的输出），用它决定这局的
    水平——没有就按中间档来。这样推演出来的表现贴着本人平时的水平，
    而不是凭空一个路人。
    """
    有数据 = bool(摘要 and 摘要.get("场数"))

    # 自己的水平：默认中间档，不假装知道他什么水平。
    基础KD = 摘要.get("KDA") or 2.0 if 有数据 else 2.0
    基础ACS = 摘要.get("场均ACS") or 220.0 if 有数据 else 220.0
    胜率 = 摘要.get("胜率") or 50.0 if 有数据 else 50.0

    # 胜负由他自己的胜率抽。交给模型抽就是连开十局全「超神」，它的随机是假的。
    # 收在 0.1~0.9：满了胜率也照样会输，一成胜率也照样会赢。
    是否胜利 = 随机源.random() < max(0.1, min(0.9, 胜率 / 100))

    if 随机源.random() < 0.12:  # 加时
        己方, 对方 = 加时比分(随机源)
    else:
        己方, 对方 = 常规比分(随机源)
    if 是否胜利 and 己方 < 对方:
        己方, 对方 = 对方, 己方
    if not 是否胜利 and 己方 > 对方:
        己方, 对方 = 对方, 己方

    回合数 = 己方 + 对方

    # K/D/A 跟着回合数走。一局 20 回合打出 5 杀或 40 杀都不像真的。
    每回合击杀 = max(0.25, min(1.35, 随机源.gauss(基础KD / 3.2, 0.18)))
    击杀 = max(1, round(回合数 * 每回合击杀 + (2 if 是否胜利 else -1)))
    死亡 = max(1, round(回合数 * random.uniform(0.45, 0.85)))
    助攻 = max(0, round(击杀 * 随机源.uniform(0.15, 0.5)))

    # ACS 围绕他自己的均值浮动，但**不随胜负大改**——输的局照样能打出高分，
    # 这是回合制的常态，别把「输」和「打得烂」绑定。
    ACS = max(40, round(随机源.gauss(基础ACS, max(25, 基础ACS * 0.18))))

    # 爆头率手掌 Start：10%~35% 是绝大多数人的区间。
    爆头率 = round(max(3.0, min(45.0, 随机源.gauss(19, 7))), 1)
    爆头数 = min(击杀, round(击杀 * 爆头率 / 100))

    定位, 特工 = 选特工(随机源)
    下包 = 随机源.randint(0, 4) if 随机源.random() < 0.55 else 0
    拆包 = 随机源.randint(0, 3) if 随机源.random() < 0.35 else 0

    # 优先打他真打过的图（名字用接口返回的原文），没有历史才用常量表。
    打过的图 = tuple(r["地图"] for r in (摘要.get("地图") or [])[:6]) if 有数据 else ()

    return {
        "地图": 选地图(随机源, 打过的图),
        "特工": 特工,
        "定位": 定位,
        "定位说明": _定位说明[定位],
        "是否胜利": 是否胜利,
        "比分": f"{己方}:{对方}",
        "加时": 回合数 > 24,
        "回合数": 回合数,
        "击杀": 击杀,
        "死亡": 死亡,
        "助攻": 助攻,
        "ACS": ACS,
        "爆头率": 爆头率,
        "爆头数": 爆头数,
        "首杀": 随机源.randint(0, max(1, round(回合数 * 0.3))),
        "下包": 下包,
        "拆包": 拆包,
        "残局": 随机源.choice(
            (
                "1v2 残局站住了",
                "1v3 被翻",
                "残局白给",
                "残局稳住防守拿下",
                "没遇到残局",
            )
        ),
        "走位": 随机源.choice(
            (
                "开局抢点激进",
                "守点架枪",
                "被打得退守",
                "绕后拿了个侧翼",
                "跟着队友进点",
            )
        ),
        "水平": (
            f"他近 {摘要['场数']} 场自己水平：KDA {摘要.get('KDA')}、ACS {摘要.get('场均ACS')}"
            if 有数据
            else "无历史数据，取中等水平"
        ),
    }


def 设定文本(设定: dict[str, Any]) -> str:
    """把设定折成给模型读的文字。"""
    行 = [
        f"模式：竞技模式{'（打到加时）' if 设定['加时'] else ''}",
        f"地图：{设定['地图']}",
        f"使用特工：{设定['特工']}（{设定['定位']}：{设定['定位说明']}）",
        f"比分：{设定['比分']}（{'胜' if 设定['是否胜利'] else '负'}），共 {设定['回合数']} 回合",
        f"击杀/死亡/助攻：{设定['击杀']}/{设定['死亡']}/{设定['助攻']}",
        f"ACS：{设定['ACS']}",
        f"爆头：{设定['爆头数']} 次，精准击败率 {设定['爆头率']}%",
        f"首杀次数：{设定['首杀']}",
        f"下包/拆包：{设定['下包']}/{设定['拆包']}",
        f"残局：{设定['残局']}",
        f"走位：{设定['走位']}",
        f"玩家水平：{设定['水平']}",
    ]
    return "\n".join(行)
